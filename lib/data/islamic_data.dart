class IslamicItem {
  final String id;
  final String category;
  final String title;
  final String arabicText;
  final String banglaPronunciation;
  final String banglaMeaning;
  final String reference;
  final String extraInfo;

  /// কুরআনের সূরা:আয়াত (যেমন '2:201' বা '2:285-286')। থাকলে অ্যাপ কুরআন থেকে আয়াত দেখায়।
  final String quranRef;

  /// অ্যাপের ভেতরে খোলার উৎস লিংক।
  final String link;

  const IslamicItem({
    required this.id,
    required this.category,
    required this.title,
    this.arabicText = '',
    this.banglaPronunciation = '',
    required this.banglaMeaning,
    this.reference = '',
    this.extraInfo = '',
    this.quranRef = '',
    this.link = '',
  });

  factory IslamicItem.fromJson(Map<String, dynamic> json) {
    return IslamicItem(
      id: (json['id'] ?? '') as String,
      category: (json['category'] ?? '') as String,
      title: (json['title'] ?? '') as String,
      arabicText: (json['arabic_text'] ?? '') as String,
      banglaPronunciation: (json['bangla_pronunciation'] ?? '') as String,
      banglaMeaning: (json['bangla_meaning'] ?? '') as String,
      reference: (json['reference'] ?? '') as String,
      extraInfo: (json['extra_info'] ?? '') as String,
      quranRef: (json['quran_ref'] ?? '') as String,
      link: (json['link'] ?? '') as String,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'category': category,
      'title': title,
      'arabic_text': arabicText,
      'bangla_pronunciation': banglaPronunciation,
      'bangla_meaning': banglaMeaning,
      'reference': reference,
      'extra_info': extraInfo,
      'quran_ref': quranRef,
      'link': link,
    };
  }
}

class IslamicCategory {
  final String id;
  final String title;
  final String subtitle;
  const IslamicCategory(this.id, this.title, this.subtitle);
}

class QuizQuestion {
  final String question;
  final List<String> options;
  final int answer;
  const QuizQuestion(this.question, this.options, this.answer);
}

class IslamicSource {
  final String group;
  final String title;
  final String subtitle;
  final String url;
  const IslamicSource(this.group, this.title, this.subtitle, this.url);
}

